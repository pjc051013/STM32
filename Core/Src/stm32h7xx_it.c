/**
  * @brief This function handles Pendable request for system service.
  */
__attribute__((naked)) void PendSV_Handler(void) {
    __asm volatile (

    /* 判断是否第一次启动 */
    "ldr   r3, =ptOS_start_first \n"
    "ldr   r2, [r3]              \n"
    "cmp   r2, #1                \n"
    "beq   first_start           \n"

    /* 普通任务切换 */
        "mrs   r0, psp               \n"
        "stmdb r0!, {r4-r11}         \n"

        "ldr   r3, =current_tcb      \n"
        "ldr   r2, [r3]              \n"
        "str   r0, [r2]              \n"

        "ldr   r3, =next_tcb         \n"
        "ldr   r2, [r3]              \n"

        "ldr   r3, =current_tcb      \n"
        "str   r2, [r3]              \n"

        "ldr   r0, [r2]              \n"
        "ldmia r0!, {r4-r11}         \n"
        "msr   psp, r0               \n"
        "bx    lr                    \n"

        /* 第一次启动 */
        "first_start:                \n"
        "movs  r2, #0                \n"
        "str   r2, [r3]              \n"

        "ldr   r3, =next_tcb         \n"
        "ldr   r3, [r3]              \n"
        "ldr   r0, [r3]              \n"

        "ldr   r1, =current_tcb      \n"
        "str   r3, [r1]              \n"

        "ldmia r0!, {r4-r11}         \n"
        "msr   psp, r0               \n"

        "movs  r0, #2                \n"
        "msr   control, r0           \n"
        "isb                         \n"

        "ldr   lr, =0xFFFFFFFD       \n"
        "bx    lr                    \n"
    );
}
